function syncLangUi() {
  const sel = document.getElementById("lang-select");
  if (sel) sel.value = currentLang;
  document.querySelectorAll('.lang-choice').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

/* Attributs traduisibles : data-i18n-placeholder / -title / -aria-label / -alt (même clé que pour un texte). */
const I18N_ATTRS = [["data-i18n-placeholder", "placeholder"], ["data-i18n-title", "title"], ["data-i18n-aria-label", "aria-label"], ["data-i18n-alt", "alt"]];
function applyAttrTranslations(root, dict) {
  if (!root) return;
  I18N_ATTRS.forEach(function (p) {
    if (root.hasAttribute && root.hasAttribute(p[0])) {
      const k0 = root.getAttribute(p[0]);
      if (dict[k0]) root.setAttribute(p[1], dict[k0]);
    }
    if (root.querySelectorAll) {
      root.querySelectorAll("[" + p[0] + "]").forEach(function (el) {
        const key = el.getAttribute(p[0]);
        if (dict[key]) el.setAttribute(p[1], dict[key]);
      });
    }
  });
}

/* Textes écrits directement en français dans certains écrans (sans data-i18n) : si un texte est EXACTEMENT un texte français
   connu du dictionnaire, on affiche sa traduction dans la langue choisie. Rien d'autre n'est touché (pas de texte partiel,
   pas de nombre, pas de zone de saisie). Le français, lui, n'est jamais modifié. */
const LIT_SKIP = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, NOSCRIPT: 1, TEMPLATE: 1, CODE: 1, PRE: 1, INPUT: 1 };
const LIT_ATTRS = ["placeholder", "title", "aria-label", "alt"];
function literalMapFor(lang) {
  if (lang === "fr" || !TRANSLATIONS[lang]) return null;
  if (litLang === lang && litMap) return litMap;
  const fr = TRANSLATIONS.fr, d = TRANSLATIONS[lang], m = new Map();
  Object.keys(fr).forEach(function (k) {
    const v = String(fr[k]).replace(/\s+/g, " ").trim();
    if (v.length < 3 || /[{<&]/.test(v) || m.has(v)) return;
    const tv = d[k];
    if (tv && tv !== fr[k]) m.set(v, tv);
  });
  // Table « texte français → traduction » des écrans internes (dans lang-xx.js, window.__cnPhrases[lang]).
  // Un texte avec {variables} devient un modèle : « {n} leçons » reconnaît « 12 leçons ».
  m.tpl = new Map(); m.tplAny = [];
  const ph = (CN_W.__cnPhrases && CN_W.__cnPhrases[lang]) || null;
  if (ph) {
    Object.keys(ph).forEach(function (k) {
      const v = ph[k];
      if (!v || typeof v !== "string") return;
      if (k.indexOf("{") < 0) { if (!m.has(k)) m.set(k, v); return; }
      const names = [];
      const parts = k.split(/\{(\w+)\}/);
      let src = "";
      for (let i = 0; i < parts.length; i++) {
        if (i % 2) { names.push(parts[i]); src += "([\\s\\S]+?)"; }
        else src += parts[i].replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      }
      let re; try { re = new RegExp("^" + src + "$"); } catch (e) { return; }
      const entry = { re: re, names: names, tr: v };
      const pre = parts[0].length >= 4 ? parts[0].slice(0, 4) : "";
      if (pre) { if (!m.tpl.has(pre)) m.tpl.set(pre, []); m.tpl.get(pre).push(entry); } else m.tplAny.push(entry);
    });
  }
  litLang = lang; litMap = m;
  return m;
}
function literalTpl(k, m) {
  const list = (m.tpl.get(k.slice(0, 4)) || []).concat(m.tplAny);
  for (let i = 0; i < list.length; i++) {
    const r = list[i].re.exec(k);
    if (!r) continue;
    let out = list[i].tr;
    list[i].names.forEach(function (nm, j) { out = out.split("{" + nm + "}").join(r[j + 1]); });
    return out;
  }
  return undefined;
}
function literalOk(el) {
  try { return !(el && el.closest && el.closest('[translate="no"],[data-no-i18n],.lang-choice,#lang-select')); } catch (e) { return true; }
}
function literalText(n, m) {
  const p = n.parentNode;
  if (!p || LIT_SKIP[p.tagName]) return;
  const raw = n.nodeValue;
  if (!raw || raw.length > 220) return;
  const k = raw.replace(/\s+/g, " ").trim();
  if (k.length < 3) return;
  let tr = m.get(k);
  if (tr === undefined && k.length > 5 && m.tpl && (m.tpl.size || m.tplAny.length)) tr = literalTpl(k, m);
  if (tr === undefined || !literalOk(p)) return;
  const mm = /^(\s*)[\s\S]*?(\s*)$/.exec(raw);
  n.nodeValue = (mm ? mm[1] : "") + tr + (mm ? mm[2] : "");
}
function literalAttrs(el, m) {
  LIT_ATTRS.forEach(function (a) {
    if (!el.hasAttribute || !el.hasAttribute(a) || el.hasAttribute("data-i18n-" + a)) return;
    const k = String(el.getAttribute(a)).replace(/\s+/g, " ").trim();
    if (k.length < 3) return;
    const tr = m.get(k);
    if (tr !== undefined && literalOk(el)) el.setAttribute(a, tr);
  });
}
function translateLiterals(root, lang) {
  try {
    const m = literalMapFor(lang);
    if (!m || !root) return;
    if (root.nodeType === 3) { literalText(root, m); return; }
    if (root.nodeType !== 1 || LIT_SKIP[root.tagName]) return;
    if (document.createTreeWalker) {
      const w = document.createTreeWalker(root, 4, null), list = [];
      let n; while ((n = w.nextNode())) list.push(n);
      list.forEach(function (x) { literalText(x, m); });
    }
    if (root.querySelectorAll) {
      root.querySelectorAll("[placeholder],[title],[aria-label],[alt]").forEach(function (el) { literalAttrs(el, m); });
    }
    literalAttrs(root, m);
  } catch (e) { /* ignore : jamais bloquant */ }
}

/* Applique la traduction à tous les éléments marqués data-i18n */
function applyTranslations(lang) {
  currentLang = lang;
  try { localStorage.setItem("coeurnoh_lang", lang); } catch (e) { /* stockage bloqué : on garde la langue pour cette visite */ }
  if (!TRANSLATIONS[lang]) { langPendingApply = lang; loadLangPack(lang); } // pack pas encore là : le français reste affiché, puis on réapplique
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  applyAttrTranslations(document, dict);
  if (document.body) translateLiterals(document.body, lang);
  document.documentElement.lang = lang;
  // Le lien « Guide » du pied de page mène à la version du guide dans la langue choisie.
  document.querySelectorAll("a[data-guide-link]").forEach(a => {
    a.setAttribute("href", (/^(en|es|it|pt)$/.test(lang) ? "/" + lang : "") + "/guide");
  });
  syncLangUi();
}

function t(key) {
  const dict = TRANSLATIONS[currentLang];
  if (dict && dict[key]) return dict[key];
  const fr = TRANSLATIONS.fr[key];
  // Kiswahili et Lingála : si une clé manquait un jour, elle s'affiche en français (langue commune en RDC), pas en anglais.
  if ((currentLang === "sw" || currentLang === "ln") && fr) return fr;
  const en = TRANSLATIONS.en && TRANSLATIONS.en[key];
  return en || fr || key;
}

/* Les écrans déjà ouverts (fil, boutique, Académie, menus…) ont été dessinés dans l'ancienne langue et beaucoup ne
   se redessinent pas seuls. Après un VRAI changement de langue, on recharge donc la page une seule fois (depuis le cache,
   moins d'une seconde) : au redémarrage, TOUT l'application démarre dans la nouvelle langue. Pas de rechargement si la
   fenêtre de connexion est ouverte (la personne est en train de remplir un formulaire : ses textes sont déjà redessinés). */
function scheduleLangRefresh() {
  try {
    if (CN_W.__cnNoLangReload) return;
    const am = document.getElementById('auth-modal');
    if (am && !am.classList.contains('hidden')) return;
    if (!CN_W.location || typeof CN_W.location.reload !== 'function') return;
    setTimeout(function () { try { CN_W.location.reload(); } catch (e) { /* ignore */ } }, 450);
  } catch (e) { /* ignore */ }
}

function finishLanguageChange(lang) {
  const previous = currentLang;
  applyTranslations(lang);
  const am = document.getElementById('auth-modal');
  if (typeof updateAuthModalMode === "function" && am && !am.classList.contains('hidden')) {
    updateAuthModalMode();
  }
  fireLangChange(lang);
  if (previous !== lang) scheduleLangRefresh();
}

/* Change la langue. Retourne une promesse (true = langue appliquée). Si le pack est déjà là, c'est immédiat.
   Si la connexion manque, la langue actuelle est gardée et un message clair s'affiche. */
function changeLanguage(lang) {
  if (SUPPORTED_LANGS.indexOf(lang) < 0) return Promise.resolve(false);
  const seq = ++langSwitchSeq;
  if (langReady(lang)) { finishLanguageChange(lang); return Promise.resolve(true); }
  let slow = setTimeout(function () {
    slow = null;
    if (seq === langSwitchSeq && typeof showToast === "function") showToast(t("common_loading"), "info", 2500);
  }, 700);
  return loadLangPack(lang).then(function (ok) {
    if (slow) clearTimeout(slow);
    if (seq !== langSwitchSeq) return false; // une autre langue a été choisie entre-temps : c'est elle qui compte
    if (!ok) {
      syncLangUi(); // le sélecteur revient sur la langue qui est vraiment affichée
      if (typeof showToast === "function") showToast(LANG_FAIL_MSG[currentLang] || LANG_FAIL_MSG.fr, "error", 5000);
      return false;
    }
    finishLanguageChange(lang);
    return true;
  });
}

/* =========================================================
   TRADUCTION AUTOMATIQUE DU CONTENU AJOUTE DYNAMIQUEMENT
   =========================================================
   Le fil, la boutique, les fenetres, etc. sont recrees en JS APRES le
   chargement initial (innerHTML) : applyTranslations() ne les voit jamais
   puisqu'elle n'inspecte le DOM qu'une fois. Cet observateur regarde le DOM
   en continu et retraduit automatiquement tout nouveau contenu marque
   data-i18n / data-i18n-placeholder, sans qu'on ait besoin d'y penser a
   chaque nouvel affichage. */
function translateNode(node, lang) {
  if (node && node.nodeType === 3) { translateLiterals(node, lang); return; }
  if (!node || node.nodeType !== 1) return;
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;

  if (node.hasAttribute && node.hasAttribute('data-i18n')) {
    const key = node.getAttribute('data-i18n');
    if (dict[key]) node.textContent = dict[key];
  }
  if (node.querySelectorAll) {
    node.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });
  }
  applyAttrTranslations(node, dict);
  translateLiterals(node, lang);
}

let i18nObserverStarted = false;
function startAutoTranslateObserver() {
  if (i18nObserverStarted) return;
  i18nObserverStarted = true;
  const observer = new MutationObserver((mutations) => {
    mutations.forEach(m => {
      m.addedNodes.forEach(node => translateNode(node, currentLang));
    });
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
if (document.body) {
  startAutoTranslateObserver();
} else {
  document.addEventListener('DOMContentLoaded', startAutoTranslateObserver);
}
