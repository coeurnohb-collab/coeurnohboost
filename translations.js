/* =========================================================
   PACKS DE LANGUE CHARGÉS À LA DEMANDE
   =========================================================
   Seul le français est dans ce fichier (il est toujours là : c'est la langue de base de l'application).
   Chaque autre langue est un petit fichier à part (lang-en.js, lang-es.js…) qui n'est téléchargé que si la personne
   la choisit. Fonctionnement :
     - index.html demande tout de suite le pack de la langue enregistrée (en parallèle du reste) ;
     - un pack, en arrivant, se range dans window.__cnPacks puis appelle window.__cnPackArrived(langue) ;
     - ce moteur le branche dans TRANSLATIONS. Peu importe quel fichier arrive le premier.
   Si un pack ne peut pas être chargé (pas de réseau), le texte reste en français, jamais vide ni « clé brute »,
   et on réessaie dès que la connexion revient. */
const SUPPORTED_LANGS = ["fr", "en", "es", "it", "pt", "sw", "ln"];
const LANG_PACKS = ["en", "es", "it", "pt", "sw", "ln"];
const LANG_PACK_TIMEOUT_MS = 12000;
const CN_W = (typeof window !== "undefined") ? window : (typeof globalThis !== "undefined" ? globalThis : {});
const LANG_FAIL_MSG = {
  fr: "Impossible de charger cette langue. Vérifie ta connexion puis réessaie.",
  en: "Couldn't load this language. Check your connection and try again.",
  es: "No se pudo cargar este idioma. Comprueba tu conexión e inténtalo de nuevo.",
  it: "Impossibile caricare questa lingua. Controlla la connessione e riprova.",
  pt: "Não foi possível carregar este idioma. Verifica a ligação e tenta de novo."
};
const langWaiters = {};      // langue -> fonctions à prévenir quand le pack est là (ou a échoué)
const langAdds = {};         // langue -> textes ajoutés par d'autres fichiers avant l'arrivée du pack
const langRetryHooked = {};
let langPendingApply = null; // langue demandée au démarrage dont le pack n'était pas encore arrivé
let langSwitchSeq = 0;

function langReady(lang) { return !!TRANSLATIONS[lang]; }

/* Ajoute un texte à une langue, même si son pack n'est pas encore chargé (ne remplace jamais un texte existant). */
let litLang = null, litMap = null; // table « texte français → traduction » (voir translateLiterals), refaite quand un pack arrive
function addTranslation(lang, key, value) {
  const d = TRANSLATIONS[lang];
  // « Existant » = texte réellement traduit dans cette langue (pour sw/ln, la copie du français n'est qu'un texte de remplacement).
  if (d) { const own = (CN_W.__cnPacks && CN_W.__cnPacks[lang]) || d; if (!own[key]) { d[key] = value; litMap = null; } return; }
  (langAdds[lang] = langAdds[lang] || {})[key] = value;
}

function fireLangChange(lang) {
  try { CN_W.dispatchEvent(new CustomEvent("cn:langchange", { detail: { lang: lang } })); } catch (e) { /* ignore */ }
}

function settleLangPack(lang, ok) {
  const list = langWaiters[lang];
  delete langWaiters[lang];
  if (list) list.forEach(function (fn) { try { fn(ok); } catch (e) { /* ignore */ } });
  if (ok && langPendingApply === lang && currentLang === lang) {
    langPendingApply = null;
    applyTranslations(lang); // le pack est arrivé après le démarrage : on affiche enfin la bonne langue
    fireLangChange(lang);
  }
}

/* Branche dans TRANSLATIONS un pack arrivé dans window.__cnPacks. Retourne true si la langue est prête. */
function registerLangPack(lang) {
  if (TRANSLATIONS[lang]) return true;
  const raw = CN_W.__cnPacks && CN_W.__cnPacks[lang];
  if (!raw) return false;
  // Kiswahili et Lingála : les packs sont complets ; la copie du français ne sert que de filet de sécurité (jamais d'écran vide).
  const d = (lang === "sw" || lang === "ln") ? Object.assign({}, TRANSLATIONS.fr, raw) : raw;
  const adds = langAdds[lang];
  if (adds) { Object.keys(adds).forEach(function (k) { if (!raw[k]) d[k] = adds[k]; }); delete langAdds[lang]; }
  TRANSLATIONS[lang] = d;
  litMap = null;
  if (CN_W.__cnPS) CN_W.__cnPS[lang] = "ok";
  settleLangPack(lang, true);
  return true;
}
CN_W.__cnPackArrived = function (lang) { registerLangPack(lang); };
CN_W.__cnPackFailed = function (lang) { packFailed(lang); };

function retryLangWhenOnline(lang) {
  if (lang !== currentLang || langRetryHooked[lang] || typeof CN_W.addEventListener !== "function") return;
  langRetryHooked[lang] = true;
  const again = function () {
    CN_W.removeEventListener("online", again);
    langRetryHooked[lang] = false;
    if (!langReady(lang) && currentLang === lang) { langPendingApply = lang; loadLangPack(lang); }
  };
  CN_W.addEventListener("online", again);
}

function packFailed(lang) {
  if (langReady(lang)) return;
  if (CN_W.__cnPS) CN_W.__cnPS[lang] = "fail";
  settleLangPack(lang, false);
  retryLangWhenOnline(lang);
}

function startLangPackRequest(lang) {
  const st = (CN_W.__cnPS = CN_W.__cnPS || {});
  if (st[lang] === "loading") return; // déjà demandé (par index.html ou par un appel précédent)
  st[lang] = "loading";
  const s = document.createElement("script");
  const v = CN_W.__cnLV && CN_W.__cnLV[lang];
  s.src = "lang-" + lang + ".js" + (v ? "?v=" + v : "");
  s.async = true;
  s.onerror = function () { packFailed(lang); };
  s.onload = function () { if (!registerLangPack(lang)) packFailed(lang); };
  (document.head || document.documentElement).appendChild(s);
}

/* Promesse : true quand le pack de la langue est prêt, false s'il n'a pas pu être chargé (délai : 12 s). */
function loadLangPack(lang) {
  if (langReady(lang)) return Promise.resolve(true);
  if (LANG_PACKS.indexOf(lang) < 0) return Promise.resolve(false);
  if (registerLangPack(lang)) return Promise.resolve(true); // le fichier était arrivé avant ce moteur
  return new Promise(function (resolve) {
    (langWaiters[lang] = langWaiters[lang] || []).push(resolve);
    startLangPackRequest(lang);
    setTimeout(function () { if (!langReady(lang)) packFailed(lang); }, LANG_PACK_TIMEOUT_MS);
  });
}

/* Exécute fn dès que la langue est prête (tout de suite si elle l'est déjà), ou après maxWaitMs au plus tard. */
function onLangReady(lang, fn, maxWaitMs) {
  if (langReady(lang)) { fn(true); return; }
  let done = false;
  const finish = function (ok) { if (done) return; done = true; fn(ok); };
  loadLangPack(lang).then(finish);
  if (maxWaitMs) setTimeout(function () { finish(false); }, maxWaitMs);
}

/* Détecte la langue du téléphone, retombe sur "en" si non supportée */
function detectLanguage() {
  let saved = null;
  try { saved = localStorage.getItem("coeurnoh_lang"); } catch (e) { saved = null; }
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  const browserLang = (navigator.language || "en").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(browserLang) ? browserLang : "en";
}

