const SUPPORTED_LANGS = ["fr", "en", "es", "it", "pt"];

/* Détecte la langue du téléphone, retombe sur "en" si non supportée */
function detectLanguage() {
  const saved = localStorage.getItem("coeurnoh_lang");
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  const browserLang = (navigator.language || "en").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(browserLang) ? browserLang : "en";
}

let currentLang = detectLanguage();

/* Applique la traduction à tous les éléments marqués data-i18n */
function applyTranslations(lang) {
  currentLang = lang;
  localStorage.setItem("coeurnoh_lang", lang);
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) el.setAttribute("placeholder", dict[key]);
  });
  document.documentElement.lang = lang;

  const sel = document.getElementById("lang-select");
  if (sel) sel.value = lang;
}

function t(key) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

function changeLanguage(lang) {
  applyTranslations(lang);
  if (typeof updateAuthModalMode === "function" && !document.getElementById('auth-modal').classList.contains('hidden')) {
    updateAuthModalMode();
  }
}
